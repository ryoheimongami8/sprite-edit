def _default_esora_cli() -> str:
    """esora-api の実行ファイルをどこから呼ぶか。

    esora_api_cli は Python 3.12 以上が必要で、このアプリの venv とは
    別に入れることになる（README 参照）。環境変数 ESORA_CLI_PATH で
    完全パスを渡せば最優先で使う。無ければ、機能4・5 の検証時に作った
    専用 venv の既定位置を探し、それも無ければ PATH 上の `esora-api` に
    賭ける（そちらの venv を有効化してからアプリを起動していれば通る）。
    """
    override = os.environ.get("ESORA_CLI_PATH")
    if override:
        return override
    for candidate in (
        r"D:\40_Esora\01_CLI\venv\Scripts\esora-api.exe",
        r"D:\40_Esora\01_CLI\venv\bin\esora-api",
    ):
        if Path(candidate).is_file():
            return candidate
    return "esora-api"


